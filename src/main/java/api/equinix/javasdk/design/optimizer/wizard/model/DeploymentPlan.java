/**
 * A complete deployment plan generated by the Deployment Wizard. Contains all
 * planned Cloud Routers, provider connections, backbone links, routing protocols,
 * and aggregated pricing. Supports review via {@link #toMarkdown()}, dry-run
 * validation via {@link #dryRun()}, and full execution via {@link #execute()}.
 */
@Value
@Builder
public class DeploymentPlan {

    /** The optimization result that drove this deployment plan. */
    OptimizationResult sourceOptimization;

    /** Cloud Routers to be created (one per metro). */
    List<PlannedCloudRouter> cloudRouters;

    /** Provider connections (Cloud Router to service profile). */
    List<PlannedConnection> providerConnections;

    /** Inter-metro backbone links (Cloud Router to Cloud Router). */
    List<PlannedBackboneLink> backboneLinks;

    /** Routing protocol configurations for all connections. */
    List<PlannedRoutingProtocol> routingProtocols;

    /** Aggregated pricing for the full deployment. */
    PlanPricing pricing;

    /** Whether the plan passed validation. */
    boolean valid;

    /** Validation errors, if any. */
    List<String> validationErrors;

    /** Reference to the Fabric client for execution. */
    @JsonIgnore
    FabricGateway fabric;

    /**
     * Total number of resources that will be created by this plan.
     */
    public int totalResourceCount() {
        int count = 0;
        if (cloudRouters != null) count += cloudRouters.size();
        if (providerConnections != null) count += providerConnections.size();
        if (backboneLinks != null) count += backboneLinks.size();
        if (routingProtocols != null) count += routingProtocols.size();
        return count;
    }

    /**
     * Generates a concise plain-text summary of the deployment plan.
     */
    public String toSummary() {
        StringBuilder sb = new StringBuilder();
        sb.append("Deployment Plan: ");
        sb.append(cloudRouters != null ? cloudRouters.size() : 0).append(" Cloud Router(s), ");
        sb.append(providerConnections != null ? providerConnections.size() : 0).append(" provider connection(s), ");
        sb.append(backboneLinks != null ? backboneLinks.size() : 0).append(" backbone link(s), ");
        sb.append(routingProtocols != null ? routingProtocols.size() : 0).append(" routing protocol(s). ");
        sb.append("Total resources: ").append(totalResourceCount()).append(".");

        if (pricing != null && pricing.getMonthlyTotal() != null) {
            sb.append(" Estimated monthly cost: $").append(pricing.getMonthlyTotal())
                    .append(" ").append(pricing.getCurrency()).append(".");
        }

        if (!valid && validationErrors != null && !validationErrors.isEmpty()) {
            sb.append(" VALIDATION ERRORS: ").append(validationErrors.size());
        }

        return sb.toString();
    }

    /**
     * Generates a full markdown-formatted deployment plan report with bandwidth
     * and pricing tables.
     */
    public String toMarkdown() {
        StringBuilder md = new StringBuilder();
        md.append("# Deployment Plan\n\n");
        md.append("_Generated from optimization computed at ").append(sourceOptimization.getComputedAt()).append("_\n\n");
        md.append("**Total Resources:** ").append(totalResourceCount()).append("\n\n");

        // Validation status
        if (!valid && validationErrors != null && !validationErrors.isEmpty()) {
            md.append("> **VALIDATION ERRORS**\n");
            for (String error : validationErrors) {
                md.append("> - ").append(error).append("\n");
            }
            md.append("\n");
        }

        // Cloud Routers
        if (cloudRouters != null && !cloudRouters.isEmpty()) {
            md.append("## Cloud Routers\n\n");
            md.append("| Name | Metro | Package |\n");
            md.append("|------|-------|---------|\n");
            for (PlannedCloudRouter cr : cloudRouters) {
                md.append("| ").append(cr.getName())
                        .append(" | ").append(cr.getMetroCode())
                        .append(" | ").append(cr.getPackageCode())
                        .append(" |\n");
            }
            md.append("\n");
        }

        // Provider Connections
        if (providerConnections != null && !providerConnections.isEmpty()) {
            md.append("## Provider Connections\n\n");
            md.append("| Name | Type | A-Side (Metro) | Z-Side (Provider) | Bandwidth | Workload Breakdown |\n");
            md.append("|------|------|----------------|-------------------|-----------|--------------------|\n");
            for (PlannedConnection conn : providerConnections) {
                md.append("| ").append(conn.getName())
                        .append(" | ").append(conn.getConnectionType())
                        .append(" | ").append(conn.getASideRouterName()).append(" (").append(conn.getASideMetro()).append(")")
                        .append(" | ").append(conn.getZSideProviderLabel());
                if (conn.getZSideSellerRegion() != null) {
                    md.append(" [").append(conn.getZSideSellerRegion()).append("]");
                }
                md.append(" | ").append(conn.getBandwidthMbps()).append(" Mbps");
                md.append(" | ");
                if (conn.getBandwidthAllocation() != null && conn.getBandwidthAllocation().getPerWorkload() != null) {
                    md.append(conn.getBandwidthAllocation().getPerWorkload().entrySet().stream()
                            .map(e -> e.getKey() + ": " + e.getValue() + " Mbps")
                            .collect(Collectors.joining(", ")));
                }
                md.append(" |\n");
            }
            md.append("\n");
        }

        // Backbone Links
        if (backboneLinks != null && !backboneLinks.isEmpty()) {
            md.append("## Backbone Links\n\n");
            md.append("| Name | Metro A | Metro Z | Bandwidth | Topology |\n");
            md.append("|------|---------|---------|-----------|----------|\n");
            for (PlannedBackboneLink link : backboneLinks) {
                md.append("| ").append(link.getName())
                        .append(" | ").append(link.getMetroA())
                        .append(" | ").append(link.getMetroZ())
                        .append(" | ").append(link.getBandwidthMbps()).append(" Mbps")
                        .append(" | ").append(link.getTopology())
                        .append(" |\n");
            }
            md.append("\n");
        }

        // Routing Protocols
        if (routingProtocols != null && !routingProtocols.isEmpty()) {
            md.append("## Routing Protocols\n\n");
            md.append("| Connection | Type | Customer Peer | Equinix Peer | ASN | BFD |\n");
            md.append("|------------|------|---------------|--------------|-----|-----|\n");
            for (PlannedRoutingProtocol rp : routingProtocols) {
                md.append("| ").append(rp.getConnectionName())
                        .append(" | ").append(rp.getType())
                        .append(" | ").append(rp.getCustomerPeerIpv4() != null ? rp.getCustomerPeerIpv4() : "-")
                        .append(" | ").append(rp.getEquinixPeerIpv4() != null ? rp.getEquinixPeerIpv4() : rp.getEquinixIfaceIpv4())
                        .append(" | ").append(rp.getCustomerAsn() != null ? rp.getCustomerAsn() : "-")
                        .append(" | ").append(rp.isBfdEnabled() ? rp.getBfdInterval() + "ms" : "off")
                        .append(" |\n");
            }
            md.append("\n");
        }

        // Pricing
        if (pricing != null) {
            md.append("## Cost Estimate\n\n");
            md.append("| Category | Monthly Cost |\n");
            md.append("|----------|-------------:|\n");
            if (pricing.getRouterMonthlyCost() != null) {
                md.append("| Cloud Routers | $").append(pricing.getRouterMonthlyCost()).append(" |\n");
            }
            if (pricing.getProviderConnectionMonthlyCost() != null) {
                md.append("| Provider Connections | $").append(pricing.getProviderConnectionMonthlyCost()).append(" |\n");
            }
            if (pricing.getBackboneMonthlyCost() != null) {
                md.append("| Backbone Links | $").append(pricing.getBackboneMonthlyCost()).append(" |\n");
            }
            if (pricing.getMonthlyTotal() != null) {
                md.append("| **Total Monthly** | **$").append(pricing.getMonthlyTotal()).append("** |\n");
            }
            if (pricing.getSetupTotal() != null) {
                md.append("| Setup (one-time) | $").append(pricing.getSetupTotal()).append(" |\n");
            }
            md.append("\n_").append(pricing.getDisclaimer()).append("_\n\n");
        }

        // Execution instructions
        md.append("## Execution\n\n");
        md.append("Resources will be created in this order:\n\n");
        md.append("1. Cloud Routers (").append(cloudRouters != null ? cloudRouters.size() : 0).append(")\n");
        md.append("2. Provider Connections (").append(providerConnections != null ? providerConnections.size() : 0).append(")\n");
        md.append("3. Backbone Links (").append(backboneLinks != null ? backboneLinks.size() : 0).append(")\n");
        md.append("4. Routing Protocols (").append(routingProtocols != null ? routingProtocols.size() : 0).append(")\n\n");
        md.append("Call `plan.dryRun()` to validate, or `plan.execute()` to provision all resources.\n");

        return md.toString();
    }

    /**
     * Begins a value-realization assessment of this plan: declare your per-provider
     * monthly egress volumes and get back the egress savings the plan's private
     * interconnects unlock, netted against the plan's actual interconnect cost.
     *
     * <pre>{@code
     * PlanValueRealization vr = plan.valueRealization()
     *     .egress(CloudProviderType.AWS, 50, DataUnit.TERABYTE)
     *     .assess();
     * System.out.println(vr.toMarkdown());
     * }</pre>
     *
     * @return a {@link PlanValueAssessment} builder for declaring egress volumes
     */
    public PlanValueAssessment valueRealization() {
        return new PlanValueAssessment(this);
    }

    /**
     * Validates the deployment plan using Fabric's dry-run API.
     * Returns a new DeploymentPlan with updated validation status.
     */
    public DeploymentPlan dryRun() {
        List<String> errors = new ArrayList<>();

        // Validate Cloud Routers with client-side field checks only. Cloud Router creation has no
        // dry-run mode, and calling create() here would provision live, billable routers — which a
        // dry run must never do — so we validate the required fields instead.
        if (cloudRouters != null) {
            for (PlannedCloudRouter cr : cloudRouters) {
                if (cr.getName() == null || cr.getName().isBlank()) {
                    errors.add("Cloud Router: missing name");
                }
                if (cr.getMetroCode() == null) {
                    errors.add("Cloud Router '" + cr.getName() + "': missing metro");
                }
                if (cr.getPackageCode() == null || cr.getPackageCode().isBlank()) {
                    errors.add("Cloud Router '" + cr.getName() + "': missing package code");
                }
            }
        }

        // Validate connections
        if (providerConnections != null) {
            for (PlannedConnection conn : providerConnections) {
                try {
                    fabric.connections().define(conn.getConnectionType())
                            .name(conn.getName())
                            .bandwidth(conn.getBandwidthMbps())
                            .dryRun()
                            .create();
                }
                catch (Exception e) {
                    errors.add("Connection '" + conn.getName() + "': " + e.getMessage());
                }
            }
        }

        return DeploymentPlan.builder()
                .sourceOptimization(sourceOptimization)
                .cloudRouters(cloudRouters)
                .providerConnections(providerConnections)
                .backboneLinks(backboneLinks)
                .routingProtocols(routingProtocols)
                .pricing(pricing)
                .valid(errors.isEmpty())
                .validationErrors(errors)
                .fabric(fabric)
                .build();
    }

    /**
     * Executes the deployment plan, creating all resources in the correct order:
     * Cloud Routers, then provider connections, then backbone links, then routing protocols.
     *
     * <p>Errors are captured in the outcome rather than thrown, allowing partial
     * deployments to be inspected and retried.</p>
     *
     * @return the execution outcome with all provisioned resources and any errors
     */
    public DeploymentOutcome execute() {
        long startTime = System.currentTimeMillis();
        List<ProvisionedResource> resources = new ArrayList<>();
        List<ProvisioningError> errors = new ArrayList<>();
        Map<String, String> routerUuids = new HashMap<>();
        Map<String, String> connectionUuids = new HashMap<>();

        // Phase 1: Create Cloud Routers
        if (cloudRouters != null) {
            for (PlannedCloudRouter planned : cloudRouters) {
                try {
                    CloudRouter cr = fabric.cloudRouters().define()
                            .name(planned.getName())
                            .inMetro(planned.getMetroCode())
                            .withPackage(planned.getPackageCode())
                            .accountNumber(planned.getAccountNumber())
                            .projectId(planned.getProjectId())
                            .create();

                    routerUuids.put(planned.getName(), cr.getUuid());
                    resources.add(ProvisionedResource.builder()
                            .resourceType("CloudRouter")
                            .name(planned.getName())
                            .uuid(cr.getUuid())
                            .metroCode(planned.getMetroCode())
                            .status("PROVISIONED")
                            .build());
                }
                catch (Exception e) {
                    errors.add(ProvisioningError.builder()
                            .resourceType("CloudRouter")
                            .resourceName(planned.getName())
                            .reason(e.getMessage())
                            .recoverable(true)
                            .build());
                }
            }
        }

        // Phase 2: Create Provider Connections
        if (providerConnections != null) {
            for (PlannedConnection planned : providerConnections) {
                try {
                    Connection conn = fabric.connections().define(planned.getConnectionType())
                            .name(planned.getName())
                            .bandwidth(planned.getBandwidthMbps())
                            .create();

                    connectionUuids.put(planned.getName(), conn.getUuid());
                    resources.add(ProvisionedResource.builder()
                            .resourceType("Connection")
                            .name(planned.getName())
                            .uuid(conn.getUuid())
                            .metroCode(planned.getASideMetro())
                            .status("PROVISIONED")
                            .build());
                }
                catch (Exception e) {
                    errors.add(ProvisioningError.builder()
                            .resourceType("Connection")
                            .resourceName(planned.getName())
                            .reason(e.getMessage())
                            .recoverable(true)
                            .build());
                }
            }
        }

        // Phase 3: Create Backbone Links
        if (backboneLinks != null) {
            for (PlannedBackboneLink link : backboneLinks) {
                PlannedConnection planned = link.getConnection();
                try {
                    Connection conn = fabric.connections().define(planned.getConnectionType())
                            .name(planned.getName())
                            .bandwidth(planned.getBandwidthMbps())
                            .create();

                    connectionUuids.put(planned.getName(), conn.getUuid());
                    resources.add(ProvisionedResource.builder()
                            .resourceType("BackboneLink")
                            .name(planned.getName())
                            .uuid(conn.getUuid())
                            .metroCode(link.getMetroA())
                            .status("PROVISIONED")
                            .build());
                }
                catch (Exception e) {
                    errors.add(ProvisioningError.builder()
                            .resourceType("BackboneLink")
                            .resourceName(planned.getName())
                            .reason(e.getMessage())
                            .recoverable(true)
                            .build());
                }
            }
        }

        // Phase 4: Create Routing Protocols
        if (routingProtocols != null) {
            for (PlannedRoutingProtocol planned : routingProtocols) {
                String connectionUuid = connectionUuids.get(planned.getConnectionName());
                if (connectionUuid == null) {
                    errors.add(ProvisioningError.builder()
                            .resourceType("RoutingProtocol")
                            .resourceName(planned.getName())
                            .reason("Parent connection '" + planned.getConnectionName() + "' was not provisioned")
                            .recoverable(false)
                            .build());
                    continue;
                }
                try {
                    var rpBuilder = fabric.routingProtocols().define()
                            .ofType(planned.getType())
                            .withName(planned.getName());

                    if (planned.getType() == RoutingProtocolType.BGP) {
                        rpBuilder.withCustomerAsn(planned.getCustomerAsn())
                                .withBGPIpv4(planned.getCustomerPeerIpv4(), planned.getEquinixPeerIpv4(), true)
                                .withBFD(planned.isBfdEnabled(), planned.getBfdInterval());
                    }
                    else if (planned.getType() == RoutingProtocolType.DIRECT) {
                        rpBuilder.withDirectIpv4(planned.getEquinixIfaceIpv4());
                    }

                    RoutingProtocol rp = rpBuilder.create(connectionUuid);
                    resources.add(ProvisionedResource.builder()
                            .resourceType("RoutingProtocol")
                            .name(planned.getName())
                            .uuid(rp.getUuid())
                            .status("PROVISIONED")
                            .build());
                }
                catch (Exception e) {
                    errors.add(ProvisioningError.builder()
                            .resourceType("RoutingProtocol")
                            .resourceName(planned.getName())
                            .reason(e.getMessage())
                            .recoverable(true)
                            .build());
                }
            }
        }

        long elapsed = System.currentTimeMillis() - startTime;
        return DeploymentOutcome.builder()
                .plan(this)
                .resources(resources)
                .fullySuccessful(errors.isEmpty())
                .errors(errors)
                .executionTimeMs(elapsed)
                .build();
    }
}
