    /** A parsed HCL block: its arguments (name to raw value) and nested blocks. */
    static final class Block {
        final String header;
        final Map<String, String> args = new LinkedHashMap<>();
        final List<Block> blocks = new ArrayList<>();

        Block(String header) {
            this.header = header;
        }

        String name() {
            return header.split("\\s+")[0];
        }

        Block child(String name) {
            return blocks.stream().filter(b -> b.name().equals(name)).findFirst().orElse(null);
        }
    }

    /**
     * Parses the exporter's HCL (one argument or block header per line) into blocks, failing on any
     * unbalanced brace, bracket or quote, and on a line that is neither comment, argument, block open
     * nor block close.
     */
    static Block parse(String hcl) {
        Block root = new Block("root");
        List<Block> stack = new ArrayList<>(List.of(root));
        int lineNo = 0;
        for (String raw : hcl.split("\n")) {
            lineNo++;
            String line = raw.trim();
            if (line.isEmpty() || line.startsWith("#")) {
                continue;
            }
            Block top = stack.get(stack.size() - 1);
            if (line.equals("}")) {
                if (stack.size() == 1) {
                    fail("unbalanced '}' at line " + lineNo);
                }
                stack.remove(stack.size() - 1);
            } else if (line.endsWith("{") && (!line.contains("=") || line.matches("[a-z_][a-z0-9_]* = \\{"))) {
                // A block header, or an object-valued argument opened on its own line ("equinix = {").
                Block b = new Block(line.substring(0, line.length() - 1).replace(" =", "").trim());
                top.blocks.add(b);
                stack.add(b);
            } else if (line.matches("[a-z_][a-z0-9_]* = .+")) {
                String name = line.substring(0, line.indexOf(" = "));
                String value = line.substring(line.indexOf(" = ") + 3);
                assertBalanced(value, lineNo);
                top.args.put(name, value);
            } else {
                fail("unparseable HCL line " + lineNo + ": " + raw);
            }
        }
        assertEquals(1, stack.size(), "every block is closed");
        return root;
    }

    private static void assertBalanced(String value, int lineNo) {
        int depth = 0;
        boolean inString = false;
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            if (inString) {
                if (c == '\\') {
                    i++;
                } else if (c == '"') {
                    inString = false;
                }
            } else if (c == '"') {
                inString = true;
            } else if (c == '[' || c == '{' || c == '(') {
                depth++;
            } else if (c == ']' || c == '}' || c == ')') {
                depth--;
                assertTrue(depth >= 0, "unbalanced value at line " + lineNo + ": " + value);
            }
        }
        assertFalse(inString, "unterminated string at line " + lineNo + ": " + value);
        assertEquals(0, depth, "unbalanced value at line " + lineNo + ": " + value);
    }

    private static void check(Block block, String path, List<String> problems) {
        Set<String> allowed = ALLOWED.get(path);
        Set<String> present = new java.util.HashSet<>(block.args.keySet());
        block.blocks.forEach(b -> present.add(b.name()));
        if (allowed != null) {
            for (String name : present) {
                if (!allowed.contains(name)) {
                    problems.add(path + "." + name + " is not a settable attribute of the provider schema");
                }
            }
        }
        for (String required : REQUIRED.getOrDefault(path, Set.of())) {
            if (!present.contains(required)) {
                problems.add(path + " is missing required " + required);
            }
        }
        for (Block child : block.blocks) {
            String childPath = child.name().equals("access_point") ? "access_point"
                    : path.equals("access_point") ? "access_point." + child.name()
                    : path + "." + child.name();
            check(child, childPath, problems);
        }
    }

    private static PlannedConnection.PlannedConnectionBuilder provider(String name, CloudProviderType cloud, String sp) {
        return PlannedConnection.builder().name(name).key("connection/DC/" + name)
                .connectionType(ConnectionType.IP_VC).purpose(ConnectionPurpose.PROVIDER).bandwidthMbps(1000)
                .aSideMetro(DC).aSideRouterName("FCR-DC").zSideServiceProfileUuid(sp).zSideProviderLabel(cloud.name())
                .zSideSellerRegion("us-east-1").zSideCloudType(cloud).notificationEmails(List.of("noc@example.com"));
    }

